const I18N = (() => {
  const KEY = "promptlab-lang";
  let lang = "es";
  try { const s = localStorage.getItem(KEY); if (s && LANG_DATA[s]) lang = s; } catch (e) {}
  const listeners = [];
  function t(key, vars = {}) {
    let s = UI[lang][key] ?? UI.es[key] ?? key;
    if (typeof s === "string") s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
    return s;
  }
  function apply() {
    document.documentElement.lang = lang;
    document.title = t("doc.title");
    document.querySelectorAll("[data-i18n]").forEach(el => { el.innerHTML = t(el.dataset.i18n); });
    document.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
    document.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); el.setAttribute("aria-label", t(el.dataset.i18nTitle)); });
    const cur = document.getElementById("lang-current"); if (cur) cur.textContent = lang.toUpperCase();
    document.querySelectorAll("#lang-menu [data-lang]").forEach(b => b.setAttribute("aria-checked", b.dataset.lang === lang ? "true" : "false"));
  }
  function set(l) {
    if (!LANG_DATA[l] || l === lang) return;
    lang = l;
    try { localStorage.setItem(KEY, l); } catch (e) {}
    apply();
    listeners.forEach(fn => fn(l));
  }
  function initPicker() {
    const btn = document.getElementById("lang-btn"), menu = document.getElementById("lang-menu");
    menu.innerHTML = Object.entries(LANG_DATA).map(([k, v]) => `<button role="menuitemradio" data-lang="${k}"><b>${k.toUpperCase()}</b> ${v.nombre}</button>`).join("");
    btn.onclick = (e) => { e.stopPropagation(); const open = menu.classList.toggle("open"); btn.setAttribute("aria-expanded", open); };
    menu.querySelectorAll("[data-lang]").forEach(b => b.onclick = () => { menu.classList.remove("open"); btn.setAttribute("aria-expanded", "false"); set(b.dataset.lang); });
    document.addEventListener("click", () => { menu.classList.remove("open"); btn.setAttribute("aria-expanded", "false"); });
  }
  return {
    t, set, apply, initPicker,
    get lang() { return lang; },
    get locale() { return LANG_DATA[lang].locale; },
    get content() { return LANG_DATA[lang].content; },
    contentOf(l) { return LANG_DATA[l].content; },
    onChange(fn) { listeners.push(fn); },
    langs: Object.keys(LANG_DATA)
  };
})();
